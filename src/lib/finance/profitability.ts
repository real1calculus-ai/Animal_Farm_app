export type ProfitabilityGroup = {
  key: string;
  label: string;
  animalCount: number;
  soldCount: number;
  costCents: number;
  revenueCents: number;
  marginCents: number;
  marginFraction: number | null;
  allocatedOverheadCents: number;
  totalGainKg: number;
  costPerKgGainCents: number | null;
  avgMarginCents: number | null;
};

function emptyGroup(key: string, label: string): ProfitabilityGroup {
  return {
    key,
    label,
    animalCount: 0,
    soldCount: 0,
    costCents: 0,
    revenueCents: 0,
    marginCents: 0,
    marginFraction: null,
    allocatedOverheadCents: 0,
    totalGainKg: 0,
    costPerKgGainCents: null,
    avgMarginCents: null,
  };
}

/**
 * Groups animals by an arbitrary key. `keyOf` returning null drops the animal
 * from that view — an animal with no sire recorded genuinely has no bloodline
 * to report against, and bucketing it under "unknown" alongside every other
 * gap invites reading noise as a finding.
 */
export function groupProfitability(
  animals: AnimalProfitability[],
  keyOf: (a: AnimalProfitability) => { key: string; label: string } | null
): ProfitabilityGroup[] {
  const groups = new Map<string, ProfitabilityGroup>();

  for (const animal of animals) {
    const bucket = keyOf(animal);
    if (!bucket) continue;

    let group = groups.get(bucket.key);
    if (!group) {
      group = emptyGroup(bucket.key, bucket.label);
      groups.set(bucket.key, group);
    }

    group.animalCount += 1;
    if (animal.soldAt) group.soldCount += 1;
    group.costCents += animal.cost.totalAttributableCents;
    group.revenueCents += animal.revenueCents;
    group.allocatedOverheadCents += animal.allocatedOverheadCents;
    if (animal.gainKg !== null && animal.gainKg > 0) group.totalGainKg += animal.gainKg;
  }

  return [...groups.values()]
    .map((group) => {
      group.marginCents = group.revenueCents - group.costCents;
      group.marginFraction =
        group.revenueCents > 0 ? group.marginCents / group.revenueCents : null;
      group.costPerKgGainCents =
        group.totalGainKg > 0 ? Math.round(group.costCents / group.totalGainKg) : null;
      group.avgMarginCents =
        group.animalCount > 0 ? Math.round(group.marginCents / group.animalCount) : null;
      return group;
    })
    .sort((a, b) => b.marginCents - a.marginCents);
}

export function byPen(animals: AnimalProfitability[]): ProfitabilityGroup[] {
  return groupProfitability(animals, (a) =>
    a.penId ? { key: a.penId, label: a.penName ?? "Pen" } : null
  );
}

export function byBreed(animals: AnimalProfitability[]): ProfitabilityGroup[] {
  return groupProfitability(animals, (a) => ({ key: a.breed, label: a.breed }));
}

/** Bloodline is taken as the sire line — the spec's "breeding line" (§5.3). */
export function byBloodline(animals: AnimalProfitability[]): ProfitabilityGroup[] {
  return groupProfitability(animals, (a) =>
    a.sireId ? { key: a.sireId, label: `Sire ${a.sireTag ?? a.sireId.slice(0, 6)}` } : null
  );
}

/** Sale month. Only sold animals appear — an unsold animal has no period. */
export function byPeriod(animals: AnimalProfitability[]): ProfitabilityGroup[] {
  return groupProfitability(animals, (a) => {
    if (!a.soldAt) return null;
    const key = `${a.soldAt.getFullYear()}-${String(a.soldAt.getMonth() + 1).padStart(2, "0")}`;
    return {
      key,
      label: a.soldAt.toLocaleDateString("en-GB", { month: "short", year: "numeric" }),
    };
  }).sort((a, b) => a.key.localeCompare(b.key));
}

