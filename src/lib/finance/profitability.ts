/**
 * Per-animal cost attribution and the aggregates built on top of it (§3.4).
 *
 * Everything here is a pure function over rows the caller has already fetched
 * (see `src/lib/db/finance.ts`). Keeping it pure is what makes the attribution
 * rules auditable: a farmer disputing a margin figure can be walked through
 * exactly which records fed it, and the rules can be exercised in tests
 * without a database.
 *
 * ---------------------------------------------------------------------------
 * WHAT IS ATTRIBUTED TO AN ANIMAL
 * ---------------------------------------------------------------------------
 *   1. Acquisition cost      — `Pig.acquisitionCostCents` (purchased animals;
 *                              null and therefore zero for born-on-farm).
 *   2. Health                — `HealthRecord.costCents` for that pig, plus the
 *                              `Medication.costCents` on those records. The two
 *                              are additive: the record cost is the visit or
 *                              procedure, the medication rows are the drugs.
 *   3. Direct feed           — `FeedingRecord` rows naming the pig.
 *   4. Shared feed           — pen-level `FeedingRecord` rows, divided by the
 *                              `animalCount` captured at feeding time, and
 *                              given only to animals that the `PenMovement`
 *                              history says were actually in that pen on that
 *                              date.
 *   5. Other direct costs    — ledger rows carrying this `pigId` that were not
 *                              generated by the health or feed modules, e.g. a
 *                              transport charge booked against one animal.
 *
 * WHAT IS DELIBERATELY *NOT* ATTRIBUTED
 *   Labour, utilities, housing, equipment, marketing and general transport are
 *   farm-level costs. Nothing in the data says which animal consumed which
 *   hour of labour, so spreading them per-head would manufacture precision the
 *   records do not contain. They are computed separately as
 *   `allocatedOverheadCents` on a days-on-farm basis and reported as their own
 *   line, never folded into `cost.totalAttributableCents`.
 *
 *   Pen feed whose `animalCount` exceeds the number of residents we can
 *   identify also stays unattributed, and is surfaced as
 *   `unattributedPenFeedCents` rather than being quietly redistributed.
 */

