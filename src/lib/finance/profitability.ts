export type ProfitabilityTotals = {
  animalCount: number;
  soldCount: number;
  costCents: number;
  revenueCents: number;
  marginCents: number;
  overheadCents: number;
  marginAfterOverheadCents: number;
  totalGainKg: number;
  /** Herd-wide cost per kg of gain — the §11.3 benchmark. */
  costPerKgGainCents: number | null;
  /** Mean realised price per kg across sold animals. */
  avgPricePerKgCents: number | null;
  /** Mean break-even weight across animals where it could be computed. */
  avgBreakEvenWeightKg: number | null;
};

export function summariseProfitability(
  result: ProfitabilityResult
): ProfitabilityTotals {
  const { animals } = result;

  let costCents = 0;
  let revenueCents = 0;
  let totalGainKg = 0;
  let soldCount = 0;
  let priceSum = 0;
  let priceCount = 0;
  let breakEvenSum = 0;
  let breakEvenCount = 0;

  for (const a of animals) {
    costCents += a.cost.totalAttributableCents;
    revenueCents += a.revenueCents;
    if (a.gainKg !== null && a.gainKg > 0) totalGainKg += a.gainKg;
    if (a.soldAt) soldCount += 1;
    if (a.pricePerKgCents !== null) {
      priceSum += a.pricePerKgCents;
      priceCount += 1;
    }
    if (a.breakEvenWeightKg !== null) {
      breakEvenSum += a.breakEvenWeightKg;
      breakEvenCount += 1;
    }
  }

  const marginCents = revenueCents - costCents;

  return {
    animalCount: animals.length,
    soldCount,
    costCents,
    revenueCents,
    marginCents,
    overheadCents: result.overheadCents,
    marginAfterOverheadCents: marginCents - result.overheadCents,
    totalGainKg,
    costPerKgGainCents: totalGainKg > 0 ? Math.round(costCents / totalGainKg) : null,
    avgPricePerKgCents: priceCount > 0 ? Math.round(priceSum / priceCount) : null,
    avgBreakEvenWeightKg: breakEvenCount > 0 ? breakEvenSum / breakEvenCount : null,
  };
}
