"use server";

import { revalidatePath } from "next/cache";

import { prisma } from "@/lib/prisma";
import { requireRole, FINANCE_ROLES } from "@/lib/auth";
import { getActiveFarmId } from "@/lib/active-farm";
import { isGeneratedRow } from "@/lib/db/finance";
import { EXPENSE_CATEGORIES, INCOME_CATEGORIES } from "@/lib/labels";
import {
  assertNotFuture,
  optionalString,
  requireCents,
  requireDate,
  requireEnum,
  requireString,
} from "@/lib/validation";

const DIRECTIONS = ["INCOME", "EXPENSE"] as const;
const ALL_CATEGORIES = [...EXPENSE_CATEGORIES, ...INCOME_CATEGORIES];

function readTransactionFields(formData: FormData) {
  const direction = requireEnum(formData, "direction", DIRECTIONS);
  const category = requireEnum(formData, "category", ALL_CATEGORIES);

  // A "feed expense" filed as income would quietly corrupt every P&L this
  // ledger feeds, and the two category lists are disjoint, so the mismatch is
  // cheap to catch here rather than confusing to explain later.
  const allowed = direction === "EXPENSE" ? EXPENSE_CATEGORIES : INCOME_CATEGORIES;
  if (!(allowed as readonly string[]).includes(category)) {
    throw new Error(`${category} is not a valid ${direction.toLowerCase()} category`);
  }

  const occurredAt = requireDate(formData, "occurredAt");
  assertNotFuture(occurredAt, "Transaction date");

  return {
    direction,
    category,
    occurredAt,
    amountCents: requireCents(formData, "amountCents"),
    description: optionalString(formData, "description"),
  };
}

/**
 * Manual ledger entry, for the costs nothing else in the system can generate
 * on its own: labour, utilities, bedding, transport, marketing. Feed
 * deliveries, health treatments, pen tasks, equipment and animal sales all
 * write their own rows from their own modules.
 */
export async function createTransaction(formData: FormData): Promise<void> {
  const user = await requireRole(FINANCE_ROLES);
  const farmId = await getActiveFarmId(user);

  await prisma.financialTransaction.create({
    data: { ...readTransactionFields(formData), farmId, createdByProfileId: user.id },
  });

  revalidatePath("/finance");
  revalidatePath("/finance/transactions");
}

/**
 * Rows generated by another module are refused here.
 *
 * A feed delivery's expense is the delivery: editing the ledger row alone
 * would leave the money and the batch disagreeing, with nothing to say which
 * is right. The fix belongs at the source record, so this points there instead
 * of silently letting the two drift apart.
 */
async function assertManualRow(id: string, farmId: string) {
  const row = await prisma.financialTransaction.findFirst({
    where: { id, farmId },
    select: {
      id: true,
      feedBatchId: true,
      healthRecordId: true,
      animalSaleId: true,
      equipmentId: true,
    },
  });
  if (!row) throw new Error("Transaction not found");

  if (isGeneratedRow(row)) {
    throw new Error(
      "This entry was created by another part of the system — a feed delivery, treatment, pen task, equipment record or animal sale. Edit it at its source record so the two cannot disagree."
    );
  }

  return row;
}

export async function updateTransaction(id: string, formData: FormData): Promise<void> {
  const user = await requireRole(FINANCE_ROLES);
  const farmId = await getActiveFarmId(user);

  await assertManualRow(id, farmId);
  await prisma.financialTransaction.update({ where: { id }, data: readTransactionFields(formData) });

  revalidatePath("/finance");
  revalidatePath("/finance/transactions");
}

export async function deleteTransaction(id: string): Promise<void> {
  const user = await requireRole(FINANCE_ROLES);
  const farmId = await getActiveFarmId(user);

  await assertManualRow(id, farmId);
  await prisma.financialTransaction.delete({ where: { id } });

  revalidatePath("/finance");
  revalidatePath("/finance/transactions");
}

export async function updateTransactionDescription(id: string, formData: FormData): Promise<void> {
  const user = await requireRole(FINANCE_ROLES);
  const farmId = await getActiveFarmId(user);

  const description = requireString(formData, "description");

  const row = await prisma.financialTransaction.findFirst({
    where: { id, farmId },
    select: { id: true },
  });
  if (!row) throw new Error("Transaction not found");

  await prisma.financialTransaction.update({ where: { id }, data: { description } });

  revalidatePath("/finance/transactions");
}
